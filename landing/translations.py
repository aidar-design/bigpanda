def gettext(key: str, lang: str) -> str:
    """Return translation for `key` in `lang`, falling back to ru, then to the key."""
    row = TRANSLATIONS.get(key)
    if row is None:
        return key
    if lang in row:
        return row[lang]
    return row.get(DEFAULT_LANG, key)


# Short alias for templates & views.
t = gettext


def normalize_lang(value: str | None) -> str:
    """Map an arbitrary string to a supported language code (default ru)."""
    if not value:
        return DEFAULT_LANG
    code = value.strip().lower()[:2]
    return code if code in SUPPORTED else DEFAULT_LANG
